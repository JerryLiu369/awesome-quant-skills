#!/usr/bin/env python3
"""Generate skills/README.md (catalog of mirrored skills).

Stdlib only. Usage:
  python3 scripts/build_catalog.py           # (re)write skills/README.md
  python3 scripts/build_catalog.py --check   # exit 1 if the file is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
OUT = SKILLS / "README.md"
REPO_URL = "https://github.com/JerryLiu369/awesome-quant-skills"
MAX_DESC = 140

CATEGORIES = {
    "alpha-factors": ("🧬", "Alpha & Factors", "因子与阿尔法"),
    "backtesting-audit": ("🧪", "Backtesting & Audit", "回测与审计"),
    "china-markets": ("🇨🇳", "China Markets", "中国市场 (A 股 / 期货)"),
    "crypto-web3": ("🪙", "Crypto & Web3", "加密与 Web3"),
    "global-equities": ("🌍", "Global Equities", "美股与全球权益"),
    "portfolio-risk": ("🛡️", "Portfolio & Risk", "组合与风控"),
}


def parse_frontmatter(text: str) -> dict[str, str]:
    """Minimal YAML subset: `key: value`, quoted values, and | / > blocks."""
    m = re.search(r"^---\s*\n(.*?)\n---\s*$", text, re.S | re.M)
    if not m:
        return {}
    out: dict[str, str] = {}
    lines = m.group(1).splitlines()
    i = 0
    while i < len(lines):
        km = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", lines[i])
        i += 1
        if not km:
            continue
        key, val = km.group(1), km.group(2).strip()
        if val in ("|", ">", "|-", ">-", "|+", ">+"):
            block = []
            while i < len(lines) and (not lines[i].strip() or lines[i][:1] in " \t"):
                block.append(lines[i].strip())
                i += 1
            val = " ".join(b for b in block if b)
        else:
            cont = []
            while i < len(lines) and lines[i][:1] in " \t" and lines[i].strip():
                cont.append(lines[i].strip())
                i += 1
            if cont:
                val = " ".join([val, *cont])
            if len(val) >= 2 and val[0] == val[-1] and val[0] in "\"'":
                val = val[1:-1]
        out[key] = val
    return out


def trim(desc: str) -> str:
    desc = re.sub(r"\s+", " ", desc).strip()
    if len(desc) > MAX_DESC:
        cut = desc[: MAX_DESC - 1]
        if " " in cut and not re.search(r"[一-鿿]", cut[-3:]):
            cut = cut.rsplit(" ", 1)[0]
        desc = cut.rstrip(" ,;:.-") + "…"
    return desc.replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")


def parse_notice() -> dict[str, tuple[str, str]]:
    """local path -> (upstream slug, license label)."""
    info: dict[str, tuple[str, str]] = {}
    for line in (ROOT / "NOTICE.md").read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\|\s*`(skills/[^`]+)`\s*\|([^|]*)\|(.*)\|\s*$", line)
        if not m:
            continue
        path, up, lic = m.group(1), m.group(2).strip(), m.group(3).strip()
        slug = re.match(r"[\w.-]+/[\w.-]+", up)
        lic = lic.replace("**", "")
        if lic.startswith("Retains upstream"):
            lic = "Upstream license"
        else:
            lic = re.split(r"\s*[(;]", lic)[0].strip() or "See NOTICE"
        info[path] = (slug.group(0) if slug else up, lic)
    return info


def build() -> str:
    notice = parse_notice()
    cats: dict[str, list[tuple[str, str, str, str, str]]] = {}
    for f in sorted(SKILLS.glob("*/*/SKILL.md")):
        text = f.read_text(encoding="utf-8")
        fm = parse_frontmatter(text)
        rel = f.relative_to(ROOT).as_posix()
        cat, dirname = f.parent.parent.name, f.parent.name
        name = fm.get("name") or dirname
        imp = re.search(r"Imported from:\s*(\S+)", text)
        slug, lic = notice.get(rel, ("", "See NOTICE"))
        url = imp.group(1) if imp else (f"https://github.com/{slug}" if slug else "")
        label = slug or re.sub(r"^https?://(www\.)?github\.com/", "", url)
        up = f"[{label}]({url})" if url else "n/a"
        cats.setdefault(cat, []).append(
            (name, f"{cat}/{dirname}/SKILL.md", trim(fm.get("description", "")), up, lic)
        )

    total = sum(len(v) for v in cats.values())
    L = [
        "<!-- GENERATED by scripts/build_catalog.py - DO NOT EDIT BY HAND. -->",
        "<!-- Regenerate: python3 scripts/build_catalog.py -->",
        "",
        "# Mirrored Skills Catalog / 镜像技能目录",
        "",
        f"> **{total} skills** in **{len(cats)} categories**, mirrored as `SKILL.md`-only "
        "excerpts from upstream projects. Each keeps its original license "
        "(see [NOTICE.md](../NOTICE.md)); companion code lives upstream.",
        "> 本目录由脚本生成，共收录镜像技能（仅 `SKILL.md`），许可证沿用上游，详见 NOTICE.md。",
        "",
        "_Generated file — do not edit by hand. Run `python3 scripts/build_catalog.py`._",
        "",
        "## Install / 安装",
        "",
        "```bash",
        "./scripts/install_skill.sh --list                          # list skills / 列出全部",
        "./scripts/install_skill.sh <skill-name> --target claude    # one skill / 单个技能",
        "./scripts/install_skill.sh <category> --target claude      # whole category / 整个分类",
        "```",
        "",
        "Targets: `claude`, `hermes`, `codex`, `opencode`, `agents`, `custom:<path>`. "
        "Add `--dry-run` to preview.",
        "",
        "## Categories / 分类",
        "",
    ]
    for cat in sorted(cats):
        e, en, zh = CATEGORIES.get(cat, ("📦", cat, cat))
        L.append(f"- {e} [{en} / {zh}](#{cat}) ({len(cats[cat])})")
    L.append("")
    for cat in sorted(cats):
        e, en, zh = CATEGORIES.get(cat, ("📦", cat, cat))
        rows = sorted(cats[cat], key=lambda r: r[0].lower())
        L += [
            f'<a id="{cat}"></a>',
            "",
            f"## {e} {en} / {zh} ({len(rows)})",
            "",
            f"Install all: `./scripts/install_skill.sh {cat} --target claude`",
            "",
            "| Skill | What it does | Upstream | License |",
            "|---|---|---|---|",
        ]
        for name, path, desc, up, lic in rows:
            L.append(f"| [`{name}`]({path}) | {desc} | {up} | {lic} |")
        L.append("")
    L += [
        "---",
        "",
        f"Back to the [main directory]({REPO_URL}#readme) / "
        "[返回主目录](../README.zh-CN.md). Contributing: [CONTRIBUTING.md](../CONTRIBUTING.md).",
        "",
    ]
    return "\n".join(L)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if skills/README.md is stale")
    args = ap.parse_args(argv)
    new = build()
    if args.check:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if cur != new:
            print("skills/README.md is stale; run: python3 scripts/build_catalog.py", file=sys.stderr)
            return 1
        print("skills/README.md is up to date.")
        return 0
    OUT.write_text(new, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
